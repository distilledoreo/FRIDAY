import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
const messages=[];
const html=await readFile(new URL('dist/artifact-editor.html',import.meta.url),'utf8');
const dom=new JSDOM(html,{runScripts:'dangerously',pretendToBeVisual:true,url:'https://editor.invalid/',beforeParse(w){w.FridayEditor={post:s=>messages.push(JSON.parse(s))};w.document.execCommand=()=>false;w.Range.prototype.getClientRects=()=>[];w.Range.prototype.getBoundingClientRect=()=>({top:0,left:0,bottom:0,right:0,width:0,height:0});}});
const {window:w}=dom;
const original={version:1,blocks:[{id:'a',type:'paragraph',text:'A 🐈 café',marks:[{type:'bold',from:2,to:3}]},{id:'b',type:'table',text:'',rows:[['one','two'],['three','four']]}]};
w.fridayInit(original,'test-session');
let last=messages.at(-1);
assert.equal(last.channel,'test-session');assert.equal(last.content.blocks[0].text,'A 🐈 café');assert.deepEqual(last.content.blocks[0].marks,[{type:'bold',from:2,to:3}]);assert.equal(last.content.blocks[1].id,'b');
const paragraph=w.document.querySelector('.ProseMirror p');
paragraph.focus();
[...w.document.querySelectorAll('button')].find(b=>b.textContent==='H1').click();
assert.equal(messages.at(-1).content.blocks[0].type,'heading');assert.equal(messages.at(-1).content.blocks[0].id,'a');
[...w.document.querySelectorAll('button')].find(b=>b.textContent==='Undo').click();
assert.equal(messages.at(-1).content.blocks[0].type,'paragraph');
assert.equal(messages.at(-1).content.blocks[0].text,'A 🐈 café');
assert.ok(html.includes("connect-src 'none'"));
assert.ok(!html.includes('https://cdn'));assert.ok(!html.includes('localStorage'));
dom.window.close();console.log('Passed: Unicode marks, stable block/table IDs, format, undo, bundled offline editor.');
